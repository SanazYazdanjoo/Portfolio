// Knowledge base for the "Ask this portfolio" assistant (api/chat.js).
//
// The assistant must never drift from what the site actually says, so its
// knowledge is DERIVED, not hand-written: this script loads the same modules
// the app renders from — data.json via profile.js, and the full case-study
// prose via src/test/fullProjects.js — through Vite's SSR runner (the same
// pattern as generate-meta.mjs, because projects.js/fullProjects.js use
// import.meta.glob).
//
// English-only, like generate-meta.mjs: the model answers German questions in
// German from English source knowledge, and a single locale halves the tokens
// sent on every chat request.
//
// Output is committed (api/_knowledge.mjs) so a deploy can never ship a chat
// function with no knowledge behind it; the build regenerates it so a content
// edit in data.json or a data.js is reflected without remembering this script
// exists.

import { createServer } from "vite";
import { writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const OUT = join(ROOT, "api", "_knowledge.mjs");

// {en, de} → en, applied recursively. Everything else passes through.
const en = (v) => {
  if (Array.isArray(v)) return v.map(en);
  if (v && typeof v === "object") {
    if ("en" in v || "de" in v) return en(v.en ?? v.de);
    return Object.fromEntries(Object.entries(v).map(([k, val]) => [k, en(val)]));
  }
  return v;
};

// Fields that carry media, layout, or app plumbing — meaningless to a
// language model and a waste of prompt tokens.
const DROP_KEYS = new Set([
  "figures", "heroImage", "heroIsGenerated", "thumbnail", "thumbnailWebp",
  "cardImage", "imagePath", "poster", "src", "aboutImage", "image",
  "navLinks", "derivedFrom", "id", "order", "conclusion", "tagEvidence",
  "prototype", "className", "span", "alt", "file", "thumb",
]);

const prune = (v) => {
  if (Array.isArray(v)) return v.map(prune);
  if (v && typeof v === "object") {
    return Object.fromEntries(
      Object.entries(v)
        .filter(([k]) => !DROP_KEYS.has(k))
        .map(([k, val]) => [k, prune(val)])
    );
  }
  return v;
};

async function main() {
  const server = await createServer({
    root: ROOT,
    server: { middlewareMode: true },
    appType: "custom",
  });

  try {
    const { profileData } = await server.ssrLoadModule("/src/data/profile.js");
    const { voluntaryItems } = await server.ssrLoadModule("/src/data/voluntary.js");
    const { fullProjects } = await server.ssrLoadModule("/src/test/fullProjects.js");

    const p = profileData;
    const profile = en(prune({
      name: p.name,
      role: p.role,
      tagline: p.tagline,
      positioning: p.positioning,
      profileSummary: p.profileSummary,
      impactStats: p.impactStats,
      bioParagraphs: p.bioParagraphs,
      experience: p.experience,
      education: p.education,
      skills: p.skills,
      languages: p.languages,
      certifications: p.certifications,
      // The phone number is deliberately left out: the site shows it in
      // context, but a chat endpoint shouldn't recite it to any bot that asks.
      contact: {
        location: p.contact.location,
        email: p.contact.email,
        linkedin: p.contact.linkedin,
        github: p.contact.github,
        website: p.contact.website,
        availability: p.contact.availability,
        timezone: p.contact.timezone,
      },
    }));

    const projects = fullProjects.map((proj) =>
      en(prune({
        title: proj.title,
        page: proj.href, // internal route the assistant links to
        status: proj.status,
        subtitle: proj.subtitle,
        tagline: proj.tagline,
        role: proj.role,
        year: proj.year,
        timeline: proj.timeline,
        context: proj.context,
        tags: proj.tags,
        techStack: proj.techStack,
        methods: proj.methods,
        metrics: proj.metrics,
        about: proj.about,
        challenge: proj.challenge,
        solution: proj.solution,
        methodology: proj.methodology,
        results: proj.results,
        implications: proj.implications,
        outcome: proj.outcome,
        process: proj.process,
        verbatims: proj.verbatims,
        cardOutcome: proj.cardOutcome,
      }))
    );

    const knowledge = {
      profile,
      projects,
      voluntary: en(prune(voluntaryItems)),
      // Routes the assistant may link to, so it never invents a URL.
      pages: {
        home: "/", projects: "/projects", about: "/about", cv: "/cv",
        contact: "/contact", credentials: "/credentials", voluntary: "/voluntary",
      },
    };

    const body =
      "// Generated by scripts/generate-chat-knowledge.mjs — do not edit by hand.\n" +
      "// Derived from src/data/data.json and src/projects/*/data.js (English locale).\n" +
      `export default ${JSON.stringify(knowledge, null, 1)};\n`;

    await writeFile(OUT, body, "utf-8");
    console.log(
      `generate-chat-knowledge: ${projects.length} projects, ${Math.round(body.length / 1024)} KiB → api/_knowledge.mjs`
    );
  } finally {
    await server.close();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
